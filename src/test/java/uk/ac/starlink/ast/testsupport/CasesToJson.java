package uk.ac.starlink.ast.testsupport;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Iterator;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Converts the C probe tables committed in the Rust repository ({@code tests/<x>_oracle/cases.rs})
 * to JSON under {@code src/test/resources/oracle/}.
 *
 * <p>Usage, from the project root after {@code mvn test-compile}: {@code java -cp
 * target/test-classes uk.ac.starlink.ast.testsupport.CasesToJson <rust repo> <x>...}. Each
 * {@code <x>} reads {@code <rust repo>/crates/starlink-ast/tests/<x>_oracle/cases.rs} and writes
 * {@code src/test/resources/oracle/<x>.json} as {@code {"source": ..., "generator": ...,
 * "rustCommit": ..., "consts": {...}}}. Doubles are written in Java's {@code Double.toString} form,
 * which on JDK 19 and later is the shortest that reads back to the same value; NaN, the infinities
 * and C's bad value are written as the strings {@code "NaN"}, {@code "Infinity"}, {@code
 * "-Infinity"} and {@code "BAD"}. JSON is written here rather than with Jackson so the converter
 * runs from {@code target/test-classes} alone.
 */
public final class CasesToJson {

    private static final Pattern GENERATED_BY = Pattern.compile("Generated by (\\S+?\\.c)\\b");

    private CasesToJson() {}

    // A command-line program reports on the console.
    @SuppressWarnings("PMD.SystemPrintln")
    public static void main(String[] args) throws IOException, InterruptedException {
        if (args.length < 2) {
            System.err.println("usage: CasesToJson <rust repo> <oracle name>...");
            System.exit(2);
        }
        Path repo = Paths.get(args[0]);
        String commit = rustCommit(repo);
        for (int i = 1; i < args.length; i++) {
            String rel = "crates/starlink-ast/tests/" + args[i] + "_oracle/cases.rs";
            String src = new String(Files.readAllBytes(repo.resolve(rel)), StandardCharsets.UTF_8);
            Map<String, Object> consts;
            try {
                consts = RustLiteral.parse(src);
            } catch (IllegalArgumentException e) {
                throw new IllegalArgumentException(rel + ": " + e.getMessage(), e);
            }
            StringBuilder sb = new StringBuilder();
            sb.append("{\n  \"source\": ")
                    .append(toJson(rel))
                    .append(",\n  \"generator\": ")
                    .append(toJson(generator(src)))
                    .append(",\n  \"rustCommit\": ")
                    .append(toJson(commit))
                    .append(",\n  \"consts\": {");
            Iterator<Map.Entry<String, Object>> it = consts.entrySet().iterator();
            while (it.hasNext()) {
                Map.Entry<String, Object> e = it.next();
                sb.append("\n    ").append(toJson(e.getKey())).append(": ").append(toJson(e.getValue()));
                if (it.hasNext()) {
                    sb.append(',');
                }
            }
            sb.append("\n  }\n}\n");
            Path out = Paths.get("src", "test", "resources", "oracle", args[i] + ".json");
            Files.createDirectories(out.getParent());
            Files.write(out, sb.toString().getBytes(StandardCharsets.UTF_8));
            System.out.println("Wrote " + out + " (" + consts.size() + " constants)");
        }
    }

    private static String rustCommit(Path repo) throws IOException, InterruptedException {
        Process p = new ProcessBuilder("git", "-C", repo.toString(), "rev-parse", "HEAD")
                .redirectErrorStream(true)
                .start();
        ByteArrayOutputStream buf = new ByteArrayOutputStream();
        try (InputStream in = p.getInputStream()) {
            byte[] chunk = new byte[256];
            int n;
            while ((n = in.read(chunk)) > 0) {
                buf.write(chunk, 0, n);
            }
        }
        String out = new String(buf.toByteArray(), StandardCharsets.UTF_8).trim();
        if (p.waitFor() != 0) {
            throw new IOException("git rev-parse failed in " + repo + ": " + out);
        }
        return out;
    }

    /** The generator named in a {@code cases.rs} header ({@code // Generated by <path>.c ...}). */
    static String generator(String src) {
        Matcher m = GENERATED_BY.matcher(src);
        if (!m.find()) {
            throw new IllegalArgumentException("No \"Generated by <program>.c\" line");
        }
        return m.group(1);
    }

    /** The JSON text of a value from {@link RustLiteral}. */
    static String toJson(Object v) {
        StringBuilder sb = new StringBuilder();
        write(sb, v);
        return sb.toString();
    }

    private static void write(StringBuilder sb, Object v) {
        if (v == null) {
            sb.append("null");
        } else if (v instanceof Double) {
            double d = (Double) v;
            if (Double.isNaN(d)) {
                sb.append("\"NaN\"");
            } else if (d == Double.POSITIVE_INFINITY) {
                sb.append("\"Infinity\"");
            } else if (d == Double.NEGATIVE_INFINITY) {
                sb.append("\"-Infinity\"");
            } else if (d == CValues.BAD) {
                sb.append("\"BAD\"");
            } else {
                sb.append(Double.toString(d));
            }
        } else if (v instanceof Long || v instanceof BigInteger || v instanceof Boolean) {
            sb.append(v);
        } else if (v instanceof String) {
            writeString(sb, (String) v);
        } else if (v instanceof List) {
            sb.append('[');
            boolean first = true;
            for (Object o : (List<?>) v) {
                if (!first) {
                    sb.append(',');
                }
                first = false;
                write(sb, o);
            }
            sb.append(']');
        } else if (v instanceof Map) {
            sb.append('{');
            boolean first = true;
            for (Map.Entry<?, ?> e : ((Map<?, ?>) v).entrySet()) {
                if (!first) {
                    sb.append(',');
                }
                first = false;
                writeString(sb, (String) e.getKey());
                sb.append(':');
                write(sb, e.getValue());
            }
            sb.append('}');
        } else {
            // MODERN-JAVA(21): sealed value type with a pattern-matching switch
            throw new IllegalArgumentException(
                    "Unexpected value type " + v.getClass().getName());
        }
    }

    private static void writeString(StringBuilder sb, String s) {
        sb.append('"');
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"':
                    sb.append("\\\"");
                    break;
                case '\\':
                    sb.append("\\\\");
                    break;
                case '\n':
                    sb.append("\\n");
                    break;
                case '\r':
                    sb.append("\\r");
                    break;
                case '\t':
                    sb.append("\\t");
                    break;
                default:
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
            }
        }
        sb.append('"');
    }
}
