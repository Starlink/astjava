package uk.ac.starlink.ast.testsupport;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.util.Arrays;
import org.junit.jupiter.api.Test;

class CasesToJsonTest {

    @Test
    void specialDoublesAreStrings() {
        assertEquals(
                "[\"NaN\",\"Infinity\",\"-Infinity\",\"BAD\",1.7976931348623157E308,2.0,1.0E-5,-0.0]",
                CasesToJson.toJson(Arrays.asList(
                        Double.NaN,
                        Double.POSITIVE_INFINITY,
                        Double.NEGATIVE_INFINITY,
                        -Double.MAX_VALUE,
                        Double.MAX_VALUE,
                        2.0,
                        1e-5,
                        -0.0)));
    }

    @Test
    void otherValues() {
        assertEquals(
                "[3,-4,true,null,\"a\\\"b\\\\c\\n\\t\\u0001é\"]",
                CasesToJson.toJson(Arrays.asList(3L, -4L, true, null, "a\"b\\c\n\t\u0001é")));
    }

    @Test
    void probeDataReversesTheEncoding() throws IOException {
        JsonNode n = new ObjectMapper().readTree("[\"NaN\",\"Infinity\",\"-Infinity\",\"BAD\",2.0,3]");
        assertEquals(Double.NaN, ProbeData.toDouble(n.get(0)));
        assertEquals(Double.POSITIVE_INFINITY, ProbeData.toDouble(n.get(1)));
        assertEquals(Double.NEGATIVE_INFINITY, ProbeData.toDouble(n.get(2)));
        assertEquals(-Double.MAX_VALUE, ProbeData.toDouble(n.get(3)));
        assertEquals(2.0, ProbeData.toDouble(n.get(4)));
        assertEquals(3.0, ProbeData.toDouble(n.get(5)));
        assertThrows(IllegalArgumentException.class, () -> ProbeData.toDouble(new ObjectMapper().readTree("\"x\"")));
    }

    @Test
    void generatorComesFromTheHeader() {
        assertEquals(
                "tools/oracle_fixtures/object_id_probe.c",
                CasesToJson.generator("// Generated by tools/oracle_fixtures/object_id_probe.c. Do not edit.\n"));
        assertEquals(
                "tools/oracle_fixtures/x_probe.c",
                CasesToJson.generator("// Copyright\n// Generated by tools/oracle_fixtures/x_probe.c against\n"));
        assertThrows(IllegalArgumentException.class, () -> CasesToJson.generator("// nothing\n"));
    }
}
