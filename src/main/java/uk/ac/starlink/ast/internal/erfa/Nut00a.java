    /**
     * Nutation in longitude and obliquity, {@code {dpsi, deps}} in radians, for the TT date {@code
     * date1 + date2} (a two-part Julian Date), IAU 2000A model (MHB2000 luni-solar and planetary
     * series, without the free core nutation). The luni-solar and planetary parts use slightly
     * different Delaunay arguments, as MHB2000 does.
     */
    public static double[] nut00a(double date1, double date2) {
        // Units of 0.1 microarcsecond to radians.
        final double u2r = Erfa.ERFA_DAS2R / 1e7;

        // Interval between fundamental date J2000.0 and given date (JC).
        double t = ((date1 - Erfa.ERFA_DJ00) + date2) / Erfa.ERFA_DJC;

        // ------------------- LUNI-SOLAR NUTATION -------------------

        // Fundamental (Delaunay) arguments.

        // Mean anomaly of the Moon (IERS 2003).
        double el = Fal03.fal03(t);

        // Mean anomaly of the Sun (MHB2000).
        double elp = ((1287104.79305 + t * (129596581.0481 + t * (-0.5532 + t * (0.000136 + t * -0.00001149))))
                        % Erfa.ERFA_TURNAS)
                * Erfa.ERFA_DAS2R;

        // Mean longitude of the Moon minus that of the ascending node (IERS 2003).
        double f = Faf03.faf03(t);

        // Mean elongation of the Moon from the Sun (MHB2000).
        double d = ((1072260.70369 + t * (1602961601.2090 + t * (-6.3706 + t * (0.006593 + t * -0.00003169))))
                        % Erfa.ERFA_TURNAS)
                * Erfa.ERFA_DAS2R;

        // Mean longitude of the ascending node of the Moon (IERS 2003).
        double om = Faom03.faom03(t);

        // Summation of the luni-solar nutation series, in reverse order.
        double dp = 0.0;
        double de = 0.0;
        for (int i = Ls.XLS.length - 1; i >= 0; i--) {
            Ls x = Ls.XLS[i];

            // Argument and functions.
            double arg = (x.nl * el
                            + x.nlp * elp
                            + x.nf * f
                            + x.nd * d // codespell:ignore nd
                            + x.nom * om)
                    % Erfa.ERFA_D2PI;
            double sarg = Math.sin(arg);
            double carg = Math.cos(arg);

            // Term.
            dp += (x.sp + x.spt * t) * sarg + x.cp * carg;
            de += (x.ce + x.cet * t) * carg + x.se * sarg;
        }

        // Convert from 0.1 microarcsec units to radians.
        double dpsils = dp * u2r;
        double depsls = de * u2r;

        // ------------------- PLANETARY NUTATION -------------------

        // Mean anomaly of the Moon (MHB2000).
        double al = (2.35555598 + 8328.6914269554 * t) % Erfa.ERFA_D2PI;

        // Mean longitude of the Moon minus that of the ascending node (MHB2000).
        double af = (1.627905234 + 8433.466158131 * t) % Erfa.ERFA_D2PI;

        // Mean elongation of the Moon from the Sun (MHB2000).
        double ad = (5.198466741 + 7771.3771468121 * t) % Erfa.ERFA_D2PI;

        // Mean longitude of the ascending node of the Moon (MHB2000).
        double aom = (2.18243920 - 33.757045 * t) % Erfa.ERFA_D2PI;

        // General accumulated precession in longitude (IERS 2003).
        double apa = Fapa03.fapa03(t);

        // Planetary longitudes, Mercury through Uranus (IERS 2003).
        double alme = Fame03.fame03(t);
        double alve = Fave03.fave03(t);
        double alea = Fae03.fae03(t);
        double alma = Fama03.fama03(t);
        double alju = Faju03.faju03(t);
        double alsa = Fasa03.fasa03(t);
        double alur = Faur03.faur03(t);

        // Neptune longitude (MHB2000).
        double alne = (5.321159000 + 3.8127774000 * t) % Erfa.ERFA_D2PI;

        // Summation of the planetary nutation series, in reverse order.
        dp = 0.0;
        de = 0.0;
        for (int i = Pl.XPL.length - 1; i >= 0; i--) {
            Pl x = Pl.XPL[i];

            // Argument and functions.
            double arg = (x.nl * al
                            + x.nf * af
                            + x.nd * ad // codespell:ignore nd
                            + x.nom * aom
                            + x.nme * alme
                            + x.nve * alve
                            + x.nea * alea
                            + x.nma * alma
                            + x.nju * alju
                            + x.nsa * alsa
                            + x.nur * alur
                            + x.nne * alne
                            + x.npa * apa)
                    % Erfa.ERFA_D2PI;
            double sarg = Math.sin(arg);
            double carg = Math.cos(arg);

            // Term.
            dp += x.sp * sarg + x.cp * carg;
            de += x.se * sarg + x.ce * carg;
        }

        // Convert from 0.1 microarcsec units to radians.
        double dpsipl = dp * u2r;
        double depspl = de * u2r;

        // Add luni-solar and planetary components.
        return new double[] {dpsils + dpsipl, depsls + depspl};
    }
